import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';

const openTaalRepo = 'OpenTaal/opentaal-wordlist';
const targetedWords = ['AZE', 'ES', 'ZES'];
const wordPattern = /^[A-Za-z]{2,15}$/;

function stripHtml(value) {
  return value
    .replace(/<[^>]*>/g, '')
    .replace(/&#8291;|&#x2063;/gi, '')
    .replace(/&nbsp;/gi, ' ')
    .replace(/&amp;/gi, '&')
    .replace(/\s+/g, ' ')
    .trim();
}

async function fetchText(url, init) {
  const response = await fetch(url, {
    ...init,
    headers: { 'User-Agent': 'Wordfeud-Helper-dictionary-generator/1.0', ...init?.headers },
  });
  if (!response.ok) throw new Error(`${url} returned HTTP ${response.status}.`);
  return response.text();
}

const commit = JSON.parse(
  await fetchText(`https://api.github.com/repos/${openTaalRepo}/commits/master`),
);
const openTaalCommit = commit.sha;
if (!/^[a-f0-9]{40}$/.test(openTaalCommit)) throw new Error('Invalid OpenTaal commit SHA.');
const rawBase = `https://raw.githubusercontent.com/${openTaalRepo}/${openTaalCommit}`;
const [openTaalText, openTaalLicense] = await Promise.all([
  fetchText(`${rawBase}/wordlist.txt`),
  fetchText(`${rawBase}/LICENSE.txt`),
]);
if (!openTaalLicense.includes('Revised BSD License')) {
  throw new Error('OpenTaal license validation failed.');
}

const verification = [];
for (const word of targetedWords) {
  const body = new URLSearchParams({
    word: word.toLowerCase(),
    exact: 'zoek',
    checkthis: '',
    code: '319d',
  });
  const taaltikHtml = await fetchText('https://wordfeud.taaltik.nl/', {
    method: 'POST',
    body,
    headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
  });
  const taaltikText = stripHtml(taaltikHtml);
  const taaltikAllowed = /W\s*E\s*L\s+toegestaan/i.test(taaltikText);
  const taaltikRejected = /N\s*I\s*E\s*T\s+toegestaan/i.test(taaltikText);
  if (!taaltikAllowed && !taaltikRejected) {
    throw new Error(`TaalTik returned no verdict for ${word}.`);
  }

  const query = new URLSearchParams({
    database: 'gig_pro_wrdlst',
    wordform: word.toLowerCase(),
    part_of_speech: '',
    paradigm: 'true',
    diminutive: 'true',
    onlyvalid: 'true',
    regex: 'false',
  });
  const woordenlijstXml = await fetchText(
    `https://woordenlijst.org/MolexServe/lexicon/find_wordform?${query}`,
  );
  const officialSpelling = woordenlijstXml.includes('<found_lemmata>');
  verification.push({ word, taaltikAllowed, officialSpelling });
}

const words = new Set(
  openTaalText
    .split(/\r?\n/)
    .map((word) => word.trim())
    .filter((word) => wordPattern.test(word))
    .map((word) => word.toUpperCase()),
);
for (const item of verification) {
  if (!item.taaltikAllowed || !item.officialSpelling) {
    throw new Error(`${item.word} did not pass both targeted verification sources.`);
  }
  words.add(item.word);
}
const sortedWords = [...words].sort();
const wordsText = sortedWords.join('\n');
const retrievedAt = new Date().toISOString();
const version = `${retrievedAt.slice(0, 10).replaceAll('-', '.')}.${retrievedAt
  .slice(11, 23)
  .replaceAll(':', '')
  .replace('.', '')}`;
const dictionarySha256 = createHash('sha256').update(wordsText).digest('hex');

const outputDirectory = new URL('../../api-server/src/data/', import.meta.url);
await mkdir(outputDirectory, { recursive: true });
await writeFile(
  new URL('dutch-open-wordlist.ts', outputDirectory),
  `// Generated by generate-open-dutch-dictionary.mjs. Do not edit manually.
export const DUTCH_OPEN_WORDS_TEXT = ${JSON.stringify(wordsText)};
export const OPEN_TAAL_LICENSE_TEXT = ${JSON.stringify(openTaalLicense)};
export const DUTCH_OPEN_DICTIONARY_META = ${JSON.stringify({
    version,
    sourceName: 'OpenTaal with reviewed Wordfeud sources',
    sourceBaseUrl: 'https://github.com/OpenTaal/opentaal-wordlist',
    openTaalCommit,
    openTaalLicense: 'Revised BSD License / CC BY 3.0',
    attribution:
      'Dutch word list by Stichting OpenTaal, modified by filtering to A-Z words of 2–15 letters and adding dual-verified Wordfeud words.',
    licenseUrl: 'https://github.com/OpenTaal/opentaal-wordlist/blob/master/LICENSE.txt',
    retrievedAt,
    minLength: 2,
    maxLength: 15,
    wordCount: sortedWords.length,
    dictionarySha256,
    sources: [
      'https://github.com/OpenTaal/opentaal-wordlist',
      'https://www.wordfeudwoorden.nl/',
      'https://wordfeud.taaltik.nl/',
      'https://woordenlijst.org/',
    ],
    verification,
  }, null, 2)} as const;
`,
);
await mkdir(new URL('../data/licenses/', import.meta.url), { recursive: true });
await writeFile(new URL('../data/licenses/OpenTaal-LICENSE.txt', import.meta.url), openTaalLicense);

console.log(JSON.stringify({ wordCount: sortedWords.length, dictionarySha256, verification }, null, 2));