import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';

const outputPath = resolve(import.meta.dirname, '../data/dutch-wordlist.ts');
const letters = 'abcdefghijklmnopqrstuvwxyz'.split('');
const MAX_RESULTS = 100000;

const normalize = (word) =>
  word
    .normalize('NFD')
    .replace(/\p{M}/gu, '')
    .toUpperCase();
const isBoardWord = (word) => /^[A-Z]{2,15}$/.test(word);
const decodeHtml = (value) =>
  value
    .replace(/&(?:nbsp|#160);/gi, ' ')
    .replace(/&amp;/gi, '&')
    .replace(/&apos;|&#39;/gi, "'")
    .replace(/&quot;/gi, '"')
    .replace(/&#(\d+);/g, (_, code) => String.fromCodePoint(Number(code)));

async function fetchRequired(url) {
  const response = await fetch(url, { headers: { 'User-Agent': 'CrossLex dictionary builder' } });
  if (!response.ok) throw new Error(`Dictionary source failed: ${url} (${response.status})`);
  return await response.text();
}

async function fetchOfficialPrefix(prefix) {
  const url = new URL('https://woordenlijst.org/MolexServe/lexicon/get_suggestions');
  url.searchParams.set('database', 'gig_pro_wrdlst');
  url.searchParams.set('wordform', `${prefix}%`);
  url.searchParams.set('part_of_speech', '');
  url.searchParams.set('onlyvalid', 'true');
  url.searchParams.set('max', String(MAX_RESULTS));
  const xml = await fetchRequired(url);
  const match = xml.match(/<suggestions>([\s\S]*?)<\/suggestions>/);
  if (!match || match[1] === 'UNKNOWN') throw new Error(`No official entries for prefix ${prefix}`);
  const entries = decodeHtml(match[1]).split(' | ');
  if (entries.length >= MAX_RESULTS) {
    throw new Error(`Official source hit its result cap for prefix ${prefix}; split the query further`);
  }
  return { url: url.toString(), body: xml, entries };
}

function extractPublishedWords(html) {
  const words = [];
  for (const match of html.matchAll(/<div class="(?:w_aa|woorden)">([\s\S]*?)<\/div>/gi)) {
    const lengthMatch = match[1].match(/(\d{1,2})\s+Letters/i);
    if (!lengthMatch) continue;
    const expectedLength = Number(lengthMatch[1]);
    const entries = match[1].replace(/^.*?<\/(?:span|p)>/is, '');
    const text = decodeHtml(entries).replace(/<br\s*\/?>/gi, '\n').replace(/<[^>]+>/g, '');
    for (const candidate of text.split(/\s+/)) {
      const word = normalize(candidate);
      if (word.length === expectedLength && isBoardWord(word)) words.push(word);
    }
  }
  return words;
}

const officialPages = await Promise.all(letters.map(fetchOfficialPrefix));
const officialWords = officialPages
  .flatMap(({ entries }) => entries)
  .filter((word) => word === word.toLocaleLowerCase('nl-NL'))
  .map(normalize)
  .filter(isBoardWord);

const publishedSources = [
  ...letters.map((letter) => ({
    url: `https://www.wordfeudwoorden.nl/letter-${letter}/`,
    required: true,
  })),
  ...letters.map((letter) => ({
    url: `https://www.wordfeudhelper.nl/woordenmeteen${letter}/`,
    required: false,
  })),
];
const publishedPages = await Promise.all(
  publishedSources.map(async ({ url, required }) => {
    const body = await fetchRequired(url);
    const entries = extractPublishedWords(body);
    if (required && entries.length === 0) throw new Error(`No Wordfeud entries found at ${url}`);
    return { url, body, entries };
  }),
);
const publishedWords = publishedPages.flatMap(({ entries }) => entries);
const words = [...new Set([...officialWords, ...publishedWords])].sort();

for (const name of ['AALTER', 'AMSTERDAM', 'ROTTERDAM']) {
  if (words.includes(name)) throw new Error(`Proper-name exclusion failed: ${name}`);
}
for (const word of ['AARDAPPEL', 'GEZELLIG', 'KONIJN', 'MUZIEK', 'PYJAMA', 'QUICHE', 'XYLOFOON']) {
  if (!words.includes(word)) throw new Error(`Representative word is missing: ${word}`);
}

const snapshotHash = createHash('sha256');
for (const page of [...officialPages, ...publishedPages].sort((a, b) => a.url.localeCompare(b.url))) {
  snapshotHash.update(page.url).update('\0').update(page.body).update('\0');
}
const dictionaryHash = createHash('sha256').update(words.join('\n')).digest('hex');

const generated = `// Generated by scripts/generate-dutch-dictionary.mjs. Do not edit manually.
export const DUTCH_DICTIONARY_METADATA = {
  version: '2026-09-03',
  wordCount: ${words.length},
  officialWordCount: ${new Set(officialWords).size},
  publishedWordCount: ${new Set(publishedWords).size},
  sourceSnapshotSha256: '${snapshotHash.digest('hex')}',
  dictionarySha256: '${dictionaryHash}',
  sources: [
    'https://woordenlijst.org/zoeken/',
    'https://www.wordfeudwoorden.nl/woordenlijst/',
    'https://www.wordfeudhelper.nl/wordfeud-woordenlijst/',
  ],
} as const;

export const DUTCH_WORDS: readonly string[] = ${JSON.stringify(words, null, 2)};
`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, generated);
console.log({
  outputPath,
  wordCount: words.length,
  officialWordCount: new Set(officialWords).size,
  publishedWordCount: new Set(publishedWords).size,
});