import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';

const sourcePath = process.argv[2];
if (!sourcePath) {
  throw new Error('Usage: node scripts/generate-dutch-dictionary.mjs <OpenTaal wordlist.txt>');
}

const outputPath = resolve(import.meta.dirname, '../data/dutch-wordlist.ts');
const source = await readFile(resolve(sourcePath), 'utf8');
const normalize = (word) =>
  word
    .normalize('NFD')
    .replace(/\p{M}/gu, '')
    .toUpperCase();
const isBoardWord = (word) => /^[A-Z]{2,15}$/.test(word);

const openTaalWords = source
  .split(/\r?\n/)
  .map((word) => word.trim())
  .filter((word) => word === word.toLocaleLowerCase('nl-NL'))
  .map(normalize)
  .filter(isBoardWord);

const letters = 'abcdefghijklmnopqrstuvwxyz'.split('');
const pages = [
  ...letters.map((letter) => ({
    url: `https://www.wordfeudwoorden.nl/letter-${letter}/`,
    required: true,
  })),
  ...letters.map((letter) => ({
    url: `https://www.wordfeudhelper.nl/woordenmeteen${letter}/`,
    required: false,
  })),
];

function decodeHtml(value) {
  return value
    .replace(/&(?:nbsp|#160);/gi, ' ')
    .replace(/&amp;/gi, '&')
    .replace(/&#(\d+);/g, (_, code) => String.fromCodePoint(Number(code)));
}

function extractPublishedWords(html) {
  const words = [];
  const listPattern = /<div class="(?:w_aa|woorden)">([\s\S]*?)<\/div>/gi;
  for (const match of html.matchAll(listPattern)) {
    const lengthMatch = match[1].match(/(\d{1,2})\s+Letters/i);
    if (!lengthMatch) continue;
    const expectedLength = Number(lengthMatch[1]);
    const entries = match[1].replace(/^.*?<\/(?:span|p)>/is, '');
    const text = decodeHtml(entries).replace(/<br\s*\/?>/gi, '\n').replace(/<[^>]+>/g, '');
    for (const candidate of text.split(/\s+/)) {
      const word = normalize(candidate);
      if (word.length === expectedLength && isBoardWord(word)) words.push(word);
    }
  }
  return words;
}

const siteResults = await Promise.all(
  pages.map(async ({ url, required }) => {
    const response = await fetch(url, { headers: { 'User-Agent': 'CrossLex dictionary builder' } });
    if (!response.ok) throw new Error(`Dictionary source failed: ${url} (${response.status})`);
    const words = extractPublishedWords(await response.text());
    if (required && words.length === 0) throw new Error(`No dictionary entries found at ${url}`);
    return { url, words };
  }),
);

const publishedWords = siteResults.flatMap(({ words }) => words);
const words = [...new Set([...openTaalWords, ...publishedWords])].sort();
const rejectedNames = ['AALTER', 'AMSTERDAM', 'ROTTERDAM'];
for (const name of rejectedNames) {
  if (words.includes(name)) throw new Error(`Proper-name exclusion failed: ${name}`);
}
for (const word of ['AARDAPPEL', 'GEZELLIG', 'KONIJN', 'MUZIEK', 'PYJAMA', 'XYLOFOON']) {
  if (!words.includes(word)) throw new Error(`Representative word is missing: ${word}`);
}

const sourceHash = createHash('sha256').update(source).digest('hex');
const generated = `// Generated by scripts/generate-dutch-dictionary.mjs. Do not edit manually.
export const DUTCH_DICTIONARY_METADATA = {
  version: '2026-09-03',
  wordCount: ${words.length},
  openTaalSourceSha256: '${sourceHash}',
  publishedWordCount: ${new Set(publishedWords).size},
  sources: [
    'https://github.com/OpenTaal/opentaal-wordlist',
    'https://www.wordfeudwoorden.nl/woordenlijst/',
    'https://www.wordfeudhelper.nl/wordfeud-woordenlijst/',
  ],
} as const;

export const DUTCH_WORDS = ${JSON.stringify(words, null, 2)} as const;
`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, generated);
console.log(
  JSON.stringify(
    {
      outputPath,
      wordCount: words.length,
      openTaalWords: new Set(openTaalWords).size,
      publishedWords: new Set(publishedWords).size,
      sourceHash,
    },
    null,
    2,
  ),
);